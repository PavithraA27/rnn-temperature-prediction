"""Simple RNN project: predict tomorrow's temperature from the last 7 days.

Run:  python temperature_rnn.py
"""
import numpy as np
import matplotlib.pyplot as plt
from tensorflow import keras

np.random.seed(1)

# 1. Make 3 years of daily temperatures: a yearly wave plus random noise
import requests

# Real daily average temperature for Bengaluru (free API, no key needed)
url = ("https://archive-api.open-meteo.com/v1/archive"
       "?latitude=12.97&longitude=77.59"
       "&start_date=2023-10-01&end_date=2026-09-30"
       "&daily=temperature_2m_mean&timezone=Asia%2FKolkata")
temp = np.array(requests.get(url).json()["daily"]["temperature_2m_mean"], dtype=float)
temp = np.nan_to_num(temp, nan=np.nanmean(temp))   # fill any missing days

# 2. Scale the values to the range 0 to 1 (RNNs train better this way)
low, high = temp.min(), temp.max()
data = (temp - low) / (high - low)

# 3. Build samples: the last 7 days (input) -> the next day (answer)
WINDOW = 7
X = np.array([data[i:i + WINDOW] for i in range(len(data) - WINDOW)])
X = X.reshape(-1, WINDOW, 1)      # shape: (samples, time steps, features)
y = data[WINDOW:]

# 4. Split in time order: first 80% to train, last 20% to test
split = int(len(X) * 0.8)
X_train, X_test = X[:split], X[split:]
y_train, y_test = y[:split], y[split:]

# 5. The RNN model
model = keras.Sequential([
    keras.layers.Input(shape=(WINDOW, 1)),
    keras.layers.SimpleRNN(32),   # reads the 7 days one by one and remembers
    keras.layers.Dense(1),        # outputs the predicted temperature
])
model.compile(optimizer="adam", loss="mse")

# 6. Train
model.fit(X_train, y_train, epochs=20, batch_size=32, validation_split=0.1)

# 7. Test on days the model has never seen
pred = model.predict(X_test).ravel()
to_celsius = lambda v: v * (high - low) + low
mae = np.mean(np.abs(to_celsius(pred) - to_celsius(y_test)))
print(f"\nAverage error on test data: {mae:.2f} degrees Celsius")

# 8. Predict tomorrow from the last 7 known days
tomorrow = model.predict(data[-WINDOW:].reshape(1, WINDOW, 1))[0, 0]
print(f"Predicted temperature for tomorrow: {to_celsius(tomorrow):.1f} C")

# 9. Plot actual against predicted
plt.figure(figsize=(9, 4))
plt.plot(to_celsius(y_test), label="Actual")
plt.plot(to_celsius(pred), label="RNN prediction")
plt.xlabel("Test day")
plt.ylabel("Temperature (C)")
plt.title("Temperature prediction with a simple RNN")
plt.legend()
plt.tight_layout()
plt.savefig("result.png", dpi=130)
print("Saved the graph as result.png")
plt.show()
# 10. Forecast the next 7 days (each prediction is fed back in as input)
window = list(data[-WINDOW:])
forecast = []
for _ in range(7):
    x = np.array(window[-WINDOW:]).reshape(1, WINDOW, 1)
    nxt = model.predict(x, verbose=0)[0, 0]
    forecast.append(nxt)
    window.append(nxt)
forecast = to_celsius(np.array(forecast))

print("\nNext 7 days forecast:")
for i, t in enumerate(forecast, 1):
    print(f"  Day {i}: {t:.1f} C")

plt.figure(figsize=(9, 4))
plt.plot(range(-29, 1), to_celsius(data[-30:]), label="Last 30 days")
plt.plot(range(1, 8), forecast, "o-", label="7-day forecast")
plt.xlabel("Days from today")
plt.ylabel("Temperature (C)")
plt.title("Next 7 days forecast")
plt.legend()
plt.tight_layout()
plt.savefig("forecast.png", dpi=130)
print("Saved the forecast as forecast.png")